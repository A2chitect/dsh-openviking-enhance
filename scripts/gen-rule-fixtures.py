#!/usr/bin/env python3
"""Generate the frozen Rule-frontmatter fixtures used by the parser unit tests.

OpenViking stores a Rule as Markdown whose YAML frontmatter is produced by
`openviking/service/rule_service.py::_render_markdown`:

    yaml.safe_dump(
        metadata,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
    ).strip()

PyYAML's default `width` is 80, so any scalar with spaces longer than that is
folded onto indented continuation lines; that shape is the normal case for
English rules and is exactly what `src/host/rule-format.ts` has to parse. This
script serializes an INVENTED corpus with the server's own options and freezes
the result in `test/fixtures/rule-frontmatter.json`, together with the values
PyYAML itself parses back (`yaml.safe_load`). The unit tests then compare our
TypeScript parser against those expectations — no Python is needed to run the
tests, and no real memory content is committed.

Run with the OpenViking tool's interpreter (it is the environment that carries
the same PyYAML the server uses), e.g.:

    ~/.local/share/uv/tools/openviking/bin/python3 scripts/gen-rule-fixtures.py
    ~/.local/share/uv/tools/openviking/bin/python3 scripts/gen-rule-fixtures.py --check

`--check` regenerates in memory and exits non-zero if the frozen file differs,
which is how a PyYAML change or a stale fixture shows up. The output is
deterministic: the pseudo-random corpus is seeded.

Why this exists: PR #2's first review caught that hand-written YAML fixtures
never exercised PyYAML's width-80 folding, and the second review caught two
residual folded shapes (an apostrophe at the fold point, a blank line inside a
quoted scalar). A frozen artifact generated by the server's own serializer keeps
that evidence honest and repeatable.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE_PATH = ROOT / "test" / "fixtures" / "rule-frontmatter.json"
SEED = 20261110

# Invented vocabulary for the generated documents; never real memory content.
WORDS = (
    "run test suite license repository change documentation complete applies exception "
    "constraint rule policy source code review merge commit verify pipeline security "
    "access data user memory preview session archive scenario catalog schema evidence "
    "revision active paused archived confidence high medium low context database agent "
    "tool skill experience trajectory outcome measurement boundary handler listener "
    "request reply timeout deadline budget token prompt answer question workflow step"
).split()

STATUSES = ("active", "paused", "archived")
CONFIDENCES = ("user", "high", "medium", "low")


def sentence(rng: random.Random, minimum: int = 4, maximum: int = 26) -> str:
    """An invented sentence long enough to force PyYAML folding."""
    words = [rng.choice(WORDS) for _ in range(rng.randint(minimum, maximum))]
    text = " ".join(words)
    flavour = rng.random()
    if flavour < 0.18:
        text += ", unless the change is documentation-only."
    elif flavour < 0.32:
        text = f'The rule titled "{text}" applies.'
    elif flavour < 0.44:
        text += " 中文规则：提交前运行完整测试。"
    elif flavour < 0.58:
        text += ": extra clause #tag"
    elif flavour < 0.70:
        text += " Dogs' toys stay in the shared crate."
    return text


def metadata(rng: random.Random, index: int) -> dict[str, object]:
    """One invented Rule frontmatter object."""
    return {
        "schema": "openviking.rule/v1",
        "atomic_id": f"rule-{index:03d}-{rng.choice(WORDS)}",
        "revision": rng.randint(1, 9),
        "status": rng.choice(STATUSES),
        "scenario_id": f"scenario-{rng.choice(WORDS)}",
        "source_uris": [f"viking://user/default/resources/{rng.choice(WORDS)}.md"],
        "evidence": [],
        "updated_at": "2026-11-10T00:00:00+00:00",
        "name": sentence(rng, 2, 8),
        "confidence": rng.choice(CONFIDENCES),
        "description": sentence(rng),
        "content": sentence(rng),
        "applies_when": sentence(rng),
        "exception": "" if rng.random() < 0.4 else sentence(rng),
    }


def curated_corpus() -> list[tuple[str, dict[str, object]]]:
    """The shapes that matter, including the two genuine review snippets."""
    n1_value = (
        "Use the tool: "
        + ("x" * 50)
        + " dogs' toys and more text that keeps going well past the eighty column limit here."
    )
    n2_tail = (
        "Second line that is also quite long and will need folding somewhere well past "
        "the eighty column limit."
    )
    b1_content = (
        "Run the full test suite before reporting a change as complete, unless the change "
        "is documentation-only."
    )
    b1_description = (
        "A long description that certainly exceeds the eighty character default width and "
        "therefore wraps onto a continuation line."
    )
    b1_applies = (
        "The task modifies source code or configuration, and the change will be reported to "
        "another person as complete."
    )
    return [
        (
            "review-b1-wrapped-plain",
            {
                "schema": "openviking.rule/v1",
                "atomic_id": "project-license",
                "revision": 2,
                "status": "active",
                "scenario_id": "repository-license",
                "source_uris": ["viking://user/default/resources/LICENSE.md"],
                "evidence": [],
                "updated_at": "2026-11-09T08:00:00+00:00",
                "name": "Run the test suite before reporting done",
                "confidence": "user",
                "description": b1_description,
                "content": b1_content,
                "applies_when": b1_applies,
                "exception": "",
            },
        ),
        # The review's N1 shape: a fold lands right after an apostrophe, which
        # YAML writes as a doubled quote (`dogs''`).
        (
            "review-n1-apostrophe-fold",
            {"content": n1_value, "exception": "", "name": "Apostrophe at the fold"},
        ),
        # The review's N2 shape: two paragraphs in a quoted scalar. PyYAML writes
        # each newline in the value as one blank line.
        (
            "review-n2-multi-paragraph-quoted",
            {
                "content": "First line of the rule.\n\n" + n2_tail,
                "name": "Multi-paragraph quoted rule",
            },
        ),
        (
            "n2-one-newline-quoted",
            {"content": "Constraint: First line of the rule.\n" + n2_tail, "name": "One newline"},
        ),
        (
            "quoted-trailing-newline",
            {"content": "Constraint: A value that ends with a newline.\n", "name": "Trailing newline"},
        ),
        # A tab forces the double-quoted style; PyYAML then wraps it with an
        # ESCAPED line break (`\` at EOL + `\ ` at the start of the continuation).
        (
            "double-quoted-escaped-break",
            {
                "content": "Run\tthe full test suite before reporting a change as complete, then report it.",
                "name": "Double-quoted escaped break",
            },
        ),
        (
            "double-quoted-single-line-escapes",
            {
                "content": 'He said: "Run the full test suite before reporting a change as complete."',
                "name": "Double-quoted escapes on one line",
            },
        ),
        (
            "single-quoted-colon-hash",
            {
                "content": "Run the full test suite before reporting a change as complete: do not skip #flaky tests.",
                "name": "Single-quoted colon and hash",
            },
        ),
        (
            "block-literal-multiline",
            {
                "content": "# Rule body\n\n- first point\n- second point\n\nA closing paragraph.",
                "name": "Block literal",
            },
        ),
        (
            "block-literal-long-lines",
            {
                "content": "Paragraph one.\n\n" + ("A long block line " * 4) + "\n\nParagraph two.",
                "name": "Block literal with long lines",
            },
        ),
        (
            "unicode-wrapped",
            {
                "content": (
                    "当规则涉及中英文混排时，PyYAML 仍然按宽度折叠较长的英文片段，"
                    "so the fallback requirement must be folded back into one logical sentence."
                ),
                "name": "中英文混排 Unicode wrapped",
            },
        ),
        (
            "empty-values",
            {"content": "", "description": "", "applies_when": "", "exception": "", "name": ""},
        ),
    ]


def corpus() -> list[tuple[str, dict[str, object]]]:
    """Curated shapes plus a deterministic pseudo-random set."""
    documents = curated_corpus()
    rng = random.Random(SEED)
    for index in range(1, 15):
        documents.append((f"generated-{index:03d}", metadata(rng, index)))
    return documents


def render() -> tuple[str, dict[str, object]]:
    """Serialize the corpus with the server's options and return the JSON text."""
    try:
        import yaml  # type: ignore[import-not-found]
    except ImportError:  # pragma: no cover - tooling guidance, not a test path
        raise SystemExit(
            "PyYAML is required to generate the fixtures. Run this script with the "
            "OpenViking tool's interpreter, e.g. "
            "~/.local/share/uv/tools/openviking/bin/python3 scripts/gen-rule-fixtures.py"
        )

    documents = []
    for name, metadata in corpus():
        frontmatter = yaml.safe_dump(
            metadata,
            allow_unicode=True,
            sort_keys=False,
            default_flow_style=False,
        ).strip()
        parsed = yaml.safe_load(frontmatter)
        if parsed != metadata:
            raise SystemExit(f"fixture {name}: PyYAML round-trip changed the value")
        documents.append({"name": name, "frontmatter": frontmatter, "expected": parsed})

    payload: dict[str, object] = {
        "generated_by": "scripts/gen-rule-fixtures.py",
        "purpose": (
            "Frozen, invented Rule frontmatter serialized by the OpenViking server's own "
            "PyYAML options; the unit tests parse these documents and compare against the "
            "expected values PyYAML itself parsed back."
        ),
        "server_serializer": "openviking/service/rule_service.py::_render_markdown",
        "pyyaml_version": yaml.__version__,
        "safe_dump_options": {
            "allow_unicode": True,
            "sort_keys": False,
            "default_flow_style": False,
            "width": 80,
        },
        "options_note": (
            "width is PyYAML's default; the server does not override it. allow_unicode is "
            "the server's actual option (not all_unicode)."
        ),
        "seed": SEED,
        "content_policy": "All values are invented for parser tests; no real memory content.",
        "documents": documents,
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n", payload


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the frozen fixture is current instead of writing it")
    parser.add_argument("--output", type=Path, default=FIXTURE_PATH, help=f"fixture path (default: {FIXTURE_PATH})")
    args = parser.parse_args(argv)

    text, payload = render()
    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"[fixtures] FAIL missing {args.output}; run without --check", file=sys.stderr)
            return 1
        if current != text:
            print(f"[fixtures] FAIL {args.output} is stale; re-run this script", file=sys.stderr)
            return 1
        print(f"[fixtures] ok   {args.output} matches the server's PyYAML {payload['pyyaml_version']} output")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(
        f"[fixtures] wrote {args.output} "
        f"({len(payload['documents'])} documents, PyYAML {payload['pyyaml_version']})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
